import { createHash } from 'crypto';
import { mkdirSync, readFileSync, readdirSync, renameSync, writeFileSync } from 'fs';
import { basename, dirname, resolve } from 'path';
import type { ConsumeTypesAuth, ConsumeTypesOptions, ManifestJson, RemoteTypeTarget } from './types.js';

const DEFAULT_OUT_DIR = 'node_modules/.linkjs';
const DEFAULT_DTS_FILE = 'linkjs-remotes.d.ts';
const DEFAULT_TIMEOUT = 5000;

/** 单个远程解析后的类型信息。 */
export interface RemoteTypeInfo {
  name: string;
  manifestUrl: string;
  typesUrl: string;
  /** 用于变更去重的哈希（manifest.typesHash 优先，否则内容 sha256）。 */
  typesHash: string;
  /** 缓存文件相对 outDir 的路径（含扩展名）。 */
  cacheRel: string;
  /** 聚合声明中引用缓存文件的相对 specifier（不含扩展名），如 `./remoteApp/lib`。 */
  cacheSpec: string;
  exposes: string[];
  mode: 'development' | 'production';
}

export interface ConsumeTypesResult {
  file: string;
  remotes: RemoteTypeInfo[];
}

function sanitizeHash(hash: string): string {
  return hash.replace(/[^a-zA-Z0-9]+/g, '_').slice(0, 40) || 'types';
}

function contentHash(content: string): string {
  return `sha256-${createHash('sha256').update(content).digest('base64')}`;
}

function resolveManifestUrl(target: RemoteTypeTarget): string {
  if (target.manifestUrl) {
    return target.manifestUrl;
  }
  if (target.host) {
    return new URL('manifest.json', target.host.endsWith('/') ? target.host : `${target.host}/`).href;
  }
  throw new Error(`[linkjs] consumeTypes: remote "${target.name}" requires \`manifestUrl\` or \`host\``);
}

async function resolveToken(auth?: ConsumeTypesAuth): Promise<string | undefined> {
  const provider = auth?.token;
  if (provider == null) {
    return undefined;
  }
  const value = typeof provider === 'function' ? await provider() : provider;
  return value || undefined;
}

function withAuth(url: string, token: string | undefined, queryParam: string): string {
  if (!token) {
    return url;
  }
  const target = new URL(url);
  target.searchParams.set(queryParam, token);
  return target.href;
}

async function request(fetchImpl: typeof fetch, url: string, timeout: number): Promise<Response> {
  const controller = typeof AbortController !== 'undefined' ? new AbortController() : undefined;
  const timer = setTimeout(() => controller?.abort(), timeout);
  try {
    return await fetchImpl(url, controller ? { signal: controller.signal } : undefined);
  } finally {
    clearTimeout(timer);
  }
}

function resolveMode(target: RemoteTypeTarget, manifest: ManifestJson): 'development' | 'production' {
  if (target.mode === 'development' || target.mode === 'production') {
    return target.mode;
  }
  return manifest.mode === 'development' ? 'development' : 'production';
}

function resolveTypesPath(manifest: ManifestJson): string | undefined {
  const metaTypes = manifest.metaData?.types;
  if (typeof metaTypes === 'string' && metaTypes) {
    return metaTypes;
  }
  const entryTypes = manifest.entry?.types;
  return typeof entryTypes === 'string' && entryTypes ? entryTypes : undefined;
}

function resolveExposes(manifest: ManifestJson): string[] {
  const names = new Set<string>();
  if (Array.isArray(manifest.expose)) {
    manifest.expose.forEach((name) => names.add(name));
  }
  for (const expose of manifest.exposes ?? []) {
    if (expose?.name) {
      names.add(expose.name);
    }
  }
  return [...names];
}

/** 原子写：临时文件 + rename，避免 tsserver 读到半截内容。 */
function writeFileAtomic(file: string, content: string): void {
  mkdirSync(dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.${Date.now()}.tmp`;
  writeFileSync(tmp, content, 'utf-8');
  renameSync(tmp, file);
}

/**
 * 生成聚合声明内容：`declare module '<name>/<Expose>'` + `linkjs` 类型注册表增强。
 */
function renderRemoteTypeDeclarations(infos: RemoteTypeInfo[]): string {
  const lines: string[] = [
    '// AUTO-GENERATED by unplugin-linkjs (consumeTypes). Do not edit.',
    '// 远程 expose 的模块声明：declare module \'<remote>/<Expose>\'',
    '',
  ];
  const mapLines: string[] = [];

  for (const info of infos) {
    lines.push(`declare module ${JSON.stringify(info.name)} {`);
    lines.push(`  export * from ${JSON.stringify(info.cacheSpec)};`);
    lines.push('}');
    mapLines.push(`    ${JSON.stringify(info.name)}: typeof import(${JSON.stringify(info.name)});`);

    for (const expose of info.exposes) {
      const key = `${info.name}/${expose}`;
      lines.push('');
      lines.push(`declare module ${JSON.stringify(key)} {`);
      lines.push(`  export * from ${JSON.stringify(info.cacheSpec)};`);
      lines.push('}');
      mapLines.push(
        `    ${JSON.stringify(key)}: typeof import(${JSON.stringify(info.name)})[${JSON.stringify(expose)}];`,
      );
    }
    lines.push('');
  }

  // 全局接口合并（linkjs 以 `declare global` 声明同名接口），避免用 ambient
  // `declare module 'linkjs'` 遮蔽其真实导出。
  lines.push('interface LinkjsRemoteTypes {');
  lines.push(...mapLines);
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

/** 拉取单个远程的 manifest + d.ts 并写入缓存，返回其类型信息。 */
async function fetchRemoteType(
  target: RemoteTypeTarget,
  options: ConsumeTypesOptions,
  fetchImpl: typeof fetch,
  outDir: string,
): Promise<RemoteTypeInfo | null> {
  const timeout = options.timeout ?? DEFAULT_TIMEOUT;
  const queryParam = options.auth?.queryParam ?? 'token';
  const token = await resolveToken(options.auth);
  const manifestUrl = withAuth(resolveManifestUrl(target), token, queryParam);

  const manifestResponse = await request(fetchImpl, manifestUrl, timeout);
  if (!manifestResponse.ok) {
    throw new Error(`[linkjs] consumeTypes: failed to fetch manifest ${manifestUrl} (${manifestResponse.status})`);
  }
  const manifest = (await manifestResponse.json()) as ManifestJson;

  const typesPath = resolveTypesPath(manifest);
  if (!typesPath) {
    return null;
  }
  const typesUrl = withAuth(new URL(typesPath, manifestUrl).href, token, queryParam);

  const dtsResponse = await request(fetchImpl, typesUrl, timeout);
  if (!dtsResponse.ok) {
    throw new Error(`[linkjs] consumeTypes: failed to fetch types ${typesUrl} (${dtsResponse.status})`);
  }
  const dtsContent = await dtsResponse.text();

  const typesHash =
    typeof manifest.metaData?.typesHash === 'string' && manifest.metaData.typesHash
      ? manifest.metaData.typesHash
      : contentHash(dtsContent);
  const hashName = sanitizeHash(typesHash);
  const fileName = basename(new URL(typesUrl).pathname) || 'index.d.ts';
  const cacheRel = `${target.name}/${hashName}-${fileName}`;
  const cacheSpec = `./${cacheRel.replace(/\.d\.(ts|mts|cts)$/, '')}`;

  writeFileAtomic(resolve(outDir, cacheRel), dtsContent);

  return {
    name: target.name,
    manifestUrl,
    typesUrl,
    typesHash,
    cacheRel,
    cacheSpec,
    exposes: resolveExposes(manifest),
    mode: resolveMode(target, manifest),
  };
}

/** 校验（best-effort）宿主 tsconfig 是否纳入了聚合声明，未纳入则 warn。 */
function checkTsconfigInclude(projectRoot: string, warn: (msg: string) => void): void {
  let candidates: string[];
  try {
    candidates = readdirSync(projectRoot).filter((file) => /^tsconfig.*\.json$/.test(file));
  } catch {
    return;
  }
  if (candidates.length === 0) {
    return;
  }
  for (const file of candidates) {
    try {
      if (readFileSync(resolve(projectRoot, file), 'utf-8').includes('.linkjs')) {
        return;
      }
    } catch {
      /* ignore */
    }
  }
  warn(
    `[linkjs] consumeTypes: 生成的 "${DEFAULT_OUT_DIR}/${DEFAULT_DTS_FILE}" 未被 tsconfig 纳入，` +
      `请在 tsconfig 的 "include"/"files" 或源码中通过 /// <reference path> 引用它。`,
  );
}

/**
 * 拉取所有远程类型、写入内容寻址缓存并生成聚合声明（构建期对齐）。
 *
 * - prod：直接按 URL 拉取不可变类型文件；
 * - dev：与 prod 同流程，另由 `watchRemoteTypes` 订阅远端事件流增量刷新。
 */
async function consumeRemoteTypes(
  options: ConsumeTypesOptions,
  projectRoot: string = process.cwd(),
): Promise<ConsumeTypesResult> {
  const fetchImpl = options.fetch ?? fetch;
  const outDir = resolve(projectRoot, options.outDir ?? DEFAULT_OUT_DIR);
  const dtsFile = options.dtsFile ?? DEFAULT_DTS_FILE;

  const infos: RemoteTypeInfo[] = [];
  for (const target of options.remotes) {
    try {
      const info = await fetchRemoteType(target, options, fetchImpl, outDir);
      if (info) {
        infos.push(info);
      }
    } catch (error) {
      // 单个远程失败不阻塞：保留旧缓存，warn 继续。
      console.warn(String((error as { message?: string })?.message ?? error));
    }
  }

  const file = resolve(outDir, dtsFile);
  writeFileAtomic(file, renderRemoteTypeDeclarations(infos));

  if (options.checkTsconfig !== false) {
    checkTsconfigInclude(projectRoot, (msg) => console.warn(msg));
  }

  return { file, remotes: infos };
}

export { consumeRemoteTypes, renderRemoteTypeDeclarations, resolveManifestUrl, sanitizeHash, contentHash };
